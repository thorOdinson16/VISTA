def lead_stats(report: dict) -> dict:
    """Metrics for the answer as the system states it (first returned object leads)."""
    claims = hits = lead = 0
    per_class: dict[str, list[int]] = {}
    for c in report["clips"]:
        cl = c["claims"]
        claims += len(cl)
        hits += sum(1 for x in cl if (x["iou"] or 0) >= 0.3)
        ok = bool(cl) and (cl[0]["iou"] or 0) >= 0.3
        lead += ok
        pc = per_class.setdefault(c["class"], [0, 0])
        pc[0] += ok
        pc[1] += 1
    n = len(report["clips"])
    o = report["overall"]
    return {
        "found": o["found_rate"],
        "any_hit": o["hit_rate_iou30"],
        "lead": lead / n,
        "objects": claims / n,
        "max_objects": max(len(c["claims"]) for c in report["clips"]),
        "precision": hits / claims if claims else 0.0,
        "recall": o["mean_frame_recall"],
        "per_class": {k: f"{v[0]}/{v[1]}" for k, v in per_class.items()},
    }


