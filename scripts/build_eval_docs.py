"""Generate docs/BENCHMARK.md and docs/EVALUATION.md from docs/eval/*.json.

    python scripts/build_eval_docs.py

Every number in the generated tables comes from the raw result files, so the
documents can be regenerated after re-running any experiment.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVAL = ROOT / "docs" / "eval"

# On-demand USD/hour, us-east-1, Linux (AWS Pricing API, 2026-10-20) and the
# COOL Marketplace software fee for the m9g.xlarge listing.
PRICE = {"cool-arm": 0.19568 + 0.01, "base-arm": 0.19568, "base-x86": 0.21168}
LABEL = {
    "cool-arm": "COOL (Graviton5, m9g.xlarge)",
    "base-arm": "pip OpenCV (Graviton5, m9g.xlarge)",
    "base-x86": "pip OpenCV (x86, m8i.xlarge)",
}


def load(name: str) -> dict:
    return json.loads((EVAL / name).read_text())


def objectron_stats(report: dict) -> dict:
    claims = hits = 0
    top_ok = 0
    clips = report["clips"]
    for c in clips:
        cl = c["claims"]
        claims += len(cl)
        hits += sum(1 for x in cl if (x["iou"] or 0) >= 0.3)
        if cl:
            top = max(cl, key=lambda x: x["frame"])
            top_ok += (top["iou"] or 0) >= 0.3
    return {
        "clips": len(clips),
        "any_hit": report["overall"]["hit_rate_iou30"],
        "found": report["overall"]["found_rate"],
        "frame_recall": report["overall"]["mean_frame_recall"],
        "objects_per_query": round(claims / len(clips), 1),
        "claim_precision": round(hits / claims, 3) if claims else 0.0,
        "latest_top1": round(top_ok / len(clips), 3),
        "processing_s": report["overall"]["mean_processing_s"],
    }


def per_class_latest(report: dict) -> dict:
    out = {}
    for cls in report["per_class"]:
        cl = [c for c in report["clips"] if c["class"] == cls]
        ok = 0
        for c in cl:
            if c["claims"]:
                top = max(c["claims"], key=lambda x: x["frame"])
                ok += (top["iou"] or 0) >= 0.3
        out[cls] = f"{ok}/{len(cl)}"
    return out


def benchmark_md() -> str:
    bench = {m: load(f"bench_{m}.json") for m in ("cool-arm", "base-arm", "base-x86")}
    stages = list(bench["cool-arm"]["stages"])
    lines = [
        "# COOL / Graviton benchmark",
        "",
        "_Generated by `scripts/build_eval_docs.py` from `docs/eval/bench_*.json`._",
        "",
        "## What was measured",
        "",
        "The same OpenCV workload (`scripts/bench_cv.py`) on three instances, using one "
        "1440x1920 phone clip (Objectron `cup/batch-30/2`, 120 frames for per-frame stages). "
        "Each stage is warmed up once and timed 5 times; the table shows the median. "
        "The **pipeline** row is the full VISTA pipeline (decode, adaptive sampling, optical "
        "flow, MOG2, `cv2.dnn` YOLO, tracking, memory) on the whole 269-frame clip.",
        "",
        "| | OpenCV | Build | CPU | Price/h |",
        "|---|---|---|---|---|",
    ]
    for m, b in bench.items():
        hal = b["build"].get("Custom HAL", "").replace("YES", "").strip()
        lines.append(
            f"| {LABEL[m]} | {b['opencv_version']} | {hal} | {b['cpu']} | ${PRICE[m]:.4f} |"
        )
    lines += [
        "",
        "Prices: us-east-1 on-demand Linux (AWS Pricing API, 2026-10-20); the COOL row "
        "includes the $0.01/h Marketplace fee.",
        "",
        "## Per-stage throughput (items/s, higher is better)",
        "",
        "| Stage | COOL | pip Arm | pip x86 | COOL / pip Arm | COOL / x86 |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for s in stages:
        c, a, x = (bench[m]["stages"][s]["items_per_s"] for m in ("cool-arm", "base-arm", "base-x86"))
        lines.append(f"| {s} | {c:.1f} | {a:.1f} | {x:.1f} | {c / a:.2f}x | {c / x:.2f}x |")
    lines += ["", "## End to end", "", "| | Pipeline fps | Frames/hour | Cost per million frames |", "|---|---:|---:|---:|"]
    for m, b in bench.items():
        fps = b["pipeline"]["throughput_fps"]
        per_hour = fps * 3600
        lines.append(f"| {LABEL[m]} | {fps:.2f} | {per_hour:,.0f} | ${PRICE[m] / per_hour * 1e6:.2f} |")
    c, a, x = (bench[m]["pipeline"]["throughput_fps"] for m in ("cool-arm", "base-arm", "base-x86"))
    cost = {m: PRICE[m] / (bench[m]["pipeline"]["throughput_fps"] * 3600) * 1e6 for m in bench}

    def wins(m: str) -> int:
        return sum(
            1
            for st in stages
            if bench[m]["stages"][st]["items_per_s"] > bench["base-x86"]["stages"][st]["items_per_s"]
        )

    def behind(m: str, name: str) -> str:
        lost = [
            st
            for st in stages
            if bench[m]["stages"][st]["items_per_s"] <= bench["base-x86"]["stages"][st]["items_per_s"]
        ]
        return f"{', '.join(f'`{x}`' for x in lost)} ({name})" if lost else ""

    lines += [
        "",
        "## What the numbers say",
        "",
        f"- **Graviton beats x86 on this workload.** The Graviton5 instance runs the full pipeline "
        f"{c / x:.2f}x (COOL) / {a / x:.2f}x (pip) as fast as the m8i x86 instance and is cheaper per hour, "
        f"so cost per million frames is ${cost['base-arm']:.2f} (pip Arm) vs ${cost['base-x86']:.2f} (x86), "
        f"{(1 - cost['base-arm'] / cost['base-x86']) * 100:.0f}% lower. Per stage, COOL is faster than x86 on "
        f"{wins('cool-arm')} of {len(stages)} stages and pip Arm on {wins('base-arm')} of {len(stages)}; "
        f"x86 is ahead on " + "; ".join(x for x in (behind('cool-arm', 'COOL'), behind('base-arm', 'pip Arm')) if x) + ".",
        f"- **COOL versus stock pip OpenCV on the same Arm hardware is within noise for the full "
        f"pipeline:** {c:.2f} vs {a:.2f} fps ({(c / a - 1) * 100:+.1f}%). COOL wins clearly on ORB "
        f"feature extraction ({bench['cool-arm']['stages']['orb_features']['items_per_s'] / bench['base-arm']['stages']['orb_features']['items_per_s']:.2f}x) "
        f"and is marginally ahead on optical flow, but is slower on decode, resize and `cv2.dnn` inference. "
        f"Because COOL carries a $0.01/h fee, cost per million frames is "
        f"${cost['cool-arm']:.2f} vs ${cost['base-arm']:.2f} for pip.",
        "- **The pip arm64 wheel already ships KleidiCV** (version 26.03 in the build string above, newer than COOL's 0.7.0), "
        "so stock OpenCV on Graviton is already Arm-optimised; COOL's advantage over it is much smaller than "
        "over an unoptimised baseline.",
        "- **Detection accuracy is unchanged by the build.** COOL and pip-Arm produced identical outcomes on all 20 "
        "Objectron clips; the x86 run differed on 2 of 20 low-confidence book clips (floating-point differences in "
        "`cv2.dnn` output across architectures).",
        "",
        "## Caveats",
        "",
        "- COOL is OpenCV 5.1.0-dev; the newest pip release is 5.0.0. The comparison is COOL against what a user "
        "gets from pip, not a controlled isolate of the Arm optimisations.",
        "- One clip, one instance per configuration, 5 repeats each: no variance across instances or days. "
        "Differences of a few percent should be treated as noise.",
        "- Vendor-published figures (up to 1.68x on image processing) were not reproduced on this workload; "
        "the workload here is the real VISTA pipeline, which is dominated by decode, `cv2.dnn` and tracking.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "bash infra/launch.sh cool-arm && bash infra/deploy.sh cool-arm",
        "# on the COOL box (see docs/AWS_DEPLOYMENT.md for the environment):",
        "python scripts/bench_cv.py --video clip.MOV --model yolov8n.onnx --repeats 5 --pipeline --label cool-arm",
        "bash infra/launch.sh base-arm && bash infra/bench_box.sh base-arm",
        "bash infra/launch.sh base-x86 && bash infra/bench_box.sh base-x86",
        "python scripts/build_eval_docs.py",
        "```",
        "",
    ]
    return "\n".join(lines)


def evaluation_md() -> str:
    yolo = load("objectron_cool_2fps.json")
    owl = load("objectron_owlv2_local_2fps.json")
    ys, os_ = objectron_stats(yolo), objectron_stats(owl)
    yl, ol = per_class_latest(yolo), per_class_latest(owl)
    clips_y = load("clips_real_yolo.json")
    clips_o = load("clips_owlv2_local.json")
    lines = [
        "# Evaluation",
        "",
        "_Generated by `scripts/build_eval_docs.py` from `docs/eval/*.json`._",
        "",
        "Three evaluations, each on public or hand-checked data, with failure cases. "
        "The system under test is the VISTA pipeline as deployed: adaptive sampling at about 2 fps, "
        "Kalman/IoU tracking with appearance re-ID, persistent memory, then query, retrieval and a grounded answer.",
        "",
        "## 1. Everyday objects: Objectron, \"Where is the X?\"",
        "",
        "20 phone videos (4 each of cup, bottle, book, laptop, chair) from the Objectron test split, "
        "chosen by a fixed random seed. Ground truth is the axis-aligned hull of Objectron's projected 3D box "
        "(looser than the visible object). The question goes through the normal parser, retriever and answerer. "
        "Metrics:",
        "",
        "- **any-hit**: some returned object's last sighting overlaps the ground truth (IoU >= 0.3). Lenient.",
        "- **latest-sighting hit**: the most recent sighting among returned objects overlaps the ground truth. "
        "This is the strict answer-level metric (\"where was it last seen\").",
        "- **claim precision**: share of all returned objects whose last sighting is correct.",
        "",
        "| Detector | Found | any-hit | latest-sighting hit | Claim precision | Objects returned / query | Frame recall |",
        "|---|---:|---:|---:|---:|---:|---:|",
        f"| YOLOv8n via `cv2.dnn` (COOL box) | {ys['found']:.0%} | {ys['any_hit']:.0%} | {ys['latest_top1']:.0%} | {ys['claim_precision']:.0%} | {ys['objects_per_query']} | {ys['frame_recall']:.2f} |",
        f"| OWLv2 (open vocabulary, local GPU) | {os_['found']:.0%} | {os_['any_hit']:.0%} | {os_['latest_top1']:.0%} | {os_['claim_precision']:.0%} | {os_['objects_per_query']} | {os_['frame_recall']:.2f} |",
        "",
        "Latest-sighting hit per class:",
        "",
        "| Class | YOLOv8n | OWLv2 |",
        "|---|---:|---:|",
    ]
    for cls in yl:
        lines.append(f"| {cls} | {yl[cls]} | {ol[cls]} |")
    lines += [
        "",
        "**Reading this honestly.** The open-vocabulary detector fixes the classes a closed-set COCO model "
        "handles badly (chair, flat books). But both detectors return many fragmented objects per query "
        "(OWLv2 up to 135), so only a small share of returned objects are correct. The most likely cause is that a handheld camera orbiting an "
        "object makes the IoU tracker lose and re-create tracks (not isolated by a separate experiment). The answer is right when the system leads with the "
        "latest sighting, wrong if it simply lists everything it remembers. Consolidating track fragments is the "
        "main identified weakness.",
        "",
        "Failure cases (figures in `docs/eval/objectron_figs/`, green = ground truth, red = returned object):",
        "",
        "- `book/batch-30/0`: a book lying flat on a shop shelf is missed; a hanging packaged flashlight is reported as a notebook.",
        "- `book/batch-7/8` and `chair/batch-25/15`: not found by YOLOv8n (COCO classes handle thin/flat or atypical views poorly).",
        "- `cup/batch-49/23` (OWLv2): 135 returned objects for a single cup; `bottle/batch-33/34`: 75 for a single bottle.",
        "",
        "## 2. Tracking and memory: MOT17",
        "",
        "Four MOT17 training sequences (FRCNN detections are not used; VISTA runs its own detector): 09 (static, easier), "
        "02 and 04 (static, crowded, 1080p), 05 (moving camera, 640x480). Scored on the frames the pipeline sampled, "
        "with CLEAR-MOT and IDF1 (own implementation, unit-tested on hand-computed cases), IoU >= 0.5, "
        "distractor regions ignored. YOLOv8n on the COOL box.",
        "",
    ]
    for fps in (2, 10):
        r = load(f"mot17_cool_{fps}fps.json")
        lines += [
            f"**Sampling {fps} fps**",
            "",
            "| Sequence | MOTA | IDF1 | ID switches | Precision | Recall | Mostly tracked / lost | \"Where is the person\" grounded | Throughput |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for s in r["sequences"]:
            t, g = s["tracking"], s["locate_grounding"]
            lines.append(
                f"| {s['sequence']} ({s['resolution']}) | {t['mota']:.3f} | {t['idf1']:.3f} | {t['id_switches']} | "
                f"{t['precision']:.2f} | {t['recall']:.2f} | {t['mostly_tracked']:.2f} / {t['mostly_lost']:.2f} | "
                f"{g['grounding_accuracy']:.2f} | {s['throughput_fps']} fps |"
            )
        lines.append("")
    lines += [
        "**Reading this honestly.** Precision is high (0.8-0.9) but recall is low on crowded 1080p scenes "
        "(0.23 on MOT17-02): the likely cause is that a nano-size YOLO at 640 px input misses small pedestrians (not isolated by a separate experiment), which caps MOTA and IDF1. "
        "ID switches are highest with a moving camera (MOT17-05). Sampling at 10 fps instead of 2 fps gives small "
        "MOTA gains (+0.01 to +0.05) on all four sequences but roughly triples processing time and does not consistently reduce ID "
        "switches, so association, not only sampling, is limiting. These figures are for a lightweight memory "
        "pipeline with a small detector, not a state-of-the-art tracker.",
        "",
        "## 3. Hand-checked clips (small, qualitative)",
        "",
        "Five questions on two short clips (a desk scene; a phone charger on a bedsheet), labelled by viewing frames "
        "(`docs/eval/clips_spec.json`). Run through the real API, including the on-demand open-vocabulary re-scan. "
        "The clips are the author's own and are not distributed.",
        "",
        "| Question | Expected | YOLOv8n | OWLv2 + on-demand re-scan |",
        "|---|---|---|---|",
    ]
    for ry, ro in zip(clips_y["results"], clips_o["results"]):
        def cell(r):
            return ("PASS" if r["passed"] else "FAIL") + (f" (last seen {r['last_seen_s']} s)" if r["found"] else " (not found)")
        lines.append(f"| {ry['question']} | {ry['expect']} | {cell(ry)} | {cell(ro)} |")
    lines += [
        "",
        f"Score: YOLOv8n {clips_y['summary']['passed']}/{clips_y['summary']['total']}, "
        f"OWLv2 {clips_o['summary']['passed']}/{clips_o['summary']['total']}. "
        "Both detectors report a **printed photograph of a face as a person**; the closed-set model additionally "
        "cannot be asked about objects outside its 80 classes (power adapter, phone charger) while the on-demand "
        "open-vocabulary re-scan can.",
        "",
        "## Limitations",
        "",
        "- MOT17 covers pedestrians only; everyday-object evidence comes from 20 Objectron clips, which is a small sample "
        "(per-class n = 4, so single clips move class numbers by 25 points).",
        "- Objectron ground truth annotates only the target object, so precision for other objects cannot be measured.",
        "- The hand-checked set is tiny and labelled by one person; it illustrates behaviour, it does not measure it.",
        "- OWLv2 results were produced on a local GPU, not on the AWS COOL instance (it needs PyTorch and is not part of the COOL claim).",
        "- Cross-architecture runs differ on a few low-confidence detections (see BENCHMARK.md).",
        "",
        "## Responsible use",
        "",
        "VISTA stores video, frames and per-person tracks. A printed photo is reported as a person, so person counts "
        "and 'who' answers need human review. Video should only be processed with the consent of the people filmed; "
        "uploads can be purged by deleting the session prefix in S3 (see `docs/AWS_DEPLOYMENT.md`).",
        "",
        "## Data and licences",
        "",
        "MOT17 (MOTChallenge) and Objectron (Ahmadyan et al., CVPR 2021) are downloaded at run time and are not in the "
        "repository; only four annotated Objectron thumbnails are included, with attribution. Check each dataset's licence "
        "before redistributing anything further.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "python scripts/eval_objectron.py --classes cup bottle book laptop chair --per-class 4 --cache data/objectron",
        "python scripts/eval_mot17.py --root MOT17/train --seqs MOT17-09-FRCNN MOT17-02-FRCNN MOT17-04-FRCNN MOT17-05-FRCNN --sample-fps 2",
        "python scripts/eval_clips.py --spec docs/eval/clips_spec.json --dir .",
        "python scripts/build_eval_docs.py",
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    (ROOT / "docs" / "BENCHMARK.md").write_text(benchmark_md(), encoding="utf-8")
    (ROOT / "docs" / "EVALUATION.md").write_text(evaluation_md(), encoding="utf-8")
    print("wrote docs/BENCHMARK.md and docs/EVALUATION.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
